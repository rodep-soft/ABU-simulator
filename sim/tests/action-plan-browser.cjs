const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const P = require('../action-plan.js');
const root = path.resolve(__dirname, '../..'), output = path.join(root, 'results', `action-plan-qa-${Date.now()}`);
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge', args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root, 'field-simulator-3d.html')).href);
    await page.waitForFunction(() => fieldApp.scene3d?.diagnostics().calls > 0);
    // The receipt template assumes prepared boxes; do not inherit the normal-supply GUI default.
    await page.locator('[data-tab="strategies"]').click();
    await page.locator('#supply-mode').selectOption('ideal'); await page.locator('#apply-strategies').click();
    await page.locator('[data-tab="sequence"]').click();
    await page.locator('#program-robot').selectOption('redTR');
    await page.locator('#program-add').click();
    await page.locator('.action-row[data-index="0"] input').fill('2');
    await page.locator('.action-row[data-index="0"] input').dispatchEvent('change');
    await page.locator('#program-add').click();
    await page.locator('.action-row[data-index="1"] input').fill('3');
    await page.locator('.action-row[data-index="1"] input').dispatchEvent('change');
    await page.locator('#program-add').click();
    await page.locator('#program-apply').click();
    assert.equal(await page.evaluate(() => fieldApp.sim.config.robotPrograms.redTR.enabled), true);
    await page.locator('#next-action').click();
    await page.waitForFunction(() => fieldApp.sim.time === 2 && !document.getElementById('next-action').disabled);
    assert.equal(await page.evaluate(() => fieldApp.sim.robot('redTR').program.index), 1);
    assert.ok(await page.evaluate(() => fieldApp.sim.robot('blueBR').y < 10.65));
    assert.equal(await page.locator('.action-row[data-index="0"] input').isDisabled(), false);
    await page.locator('.action-row[data-index="0"] input').fill('4');
    await page.locator('.action-row[data-index="0"] input').dispatchEvent('change');
    await page.locator('#program-update').click();
    assert.match(await page.locator('#program-message').textContent(), /完了した手順/);
    assert.equal(await page.evaluate(() => fieldApp.sim.config.robotPrograms.redTR.steps[0].seconds), 2);
    await page.locator('.action-row[data-index="0"] input').fill('2');
    await page.locator('.action-row[data-index="0"] input').dispatchEvent('change');
    await page.locator('.action-row[data-index="1"] input').fill('.5');
    await page.locator('.action-row[data-index="1"] input').dispatchEvent('change');
    await page.locator('#program-update').click();
    assert.equal(await page.evaluate(() => fieldApp.sim.time), 2);
    await page.locator('#next-action').click();
    await page.waitForFunction(() => fieldApp.sim.time === 2.5 && !document.getElementById('next-action').disabled);
    await page.locator('#action-options-toggle').click();
    await page.locator('#pause-each-action').check();
    await page.locator('#play').click();
    await page.waitForFunction(() => fieldApp.sim.robot('redTR').program.index === 3);
    const paused = await page.evaluate(() => fieldApp.sim.time);
    await page.waitForTimeout(250); assert.equal(await page.evaluate(() => fieldApp.sim.time), paused);
    assert.equal(paused, 3.5); await page.locator('#pause-each-action').uncheck();
    const downloadPromise = page.waitForEvent('download'); await page.locator('#program-export').click(); const download = await downloadPromise;
    await download.saveAs(path.join(output, 'plans.json'));
    const saved = JSON.parse(fs.readFileSync(path.join(output, 'plans.json')));
    assert.equal(saved.format, 'robocon-action-plans-v1'); assert.equal(saved.programs.redTR.steps[1].seconds, .5);
    const steps = P.template('redBR'); steps[10].seconds = 5.5;
    const file = { format: 'robocon-action-plans-v1', programs: { redBR: { enabled: true, end: 'wait', steps } }, timing: { redBR: { receive: .35, place: 3, scan: .6 } } };
    await page.locator('#program-file').setInputFiles({ name: 'plans.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(file)) });
    await page.locator('#program-robot').selectOption('redBR');
    assert.equal(await page.locator('.action-row[data-index="10"] [data-field="seconds"]').inputValue(), '5.5');
    await page.locator('#program-apply').click();
    assert.equal(await page.evaluate(() => fieldApp.sim.time), 0);
    await page.locator('#next-action').click();
    await page.waitForFunction(() => !document.getElementById('next-action').disabled);
    assert.ok(await page.evaluate(() => fieldApp.sim.events.some(e => e.robot === 'redBR' && e.kind === 'timing' && e.action === 'move')));
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.locator('[data-tab="sequence"]').click();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.locator('#tab-sequence').screenshot({ path: path.join(output, `editor-${width}.png`) });
      await page.locator('.action-row[data-index="10"]').screenshot({ path: path.join(output, `placement-${width}.png`) });
      await page.locator('.robot-timing').screenshot({ path: path.join(output, `timing-${width}.png`) });
      await page.locator('.step-control-bar').screenshot({ path: path.join(output, `stepbar-${width}.png`) });
    }
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.locator('#finish').click(); await page.waitForFunction(() => fieldApp.sim.ended, null, { timeout: 240000 });
    const result = await page.evaluate(() => ({ time: fieldApp.sim.time, scores: fieldApp.sim.scores(),
      program: fieldApp.sim.robot('redBR').program,
      placements: fieldApp.sim.events.filter(e => e.robot === 'redBR' && e.kind === 'timing' && e.action === 'place').map(e => ({ spotId: e.spotId, duration: e.duration })),
      receipts: fieldApp.sim.events.filter(e => e.robot === 'redBR' && e.kind === 'timing' && e.action === 'receive').map(e => e.duration) }));
    assert.equal(result.time, 180); assert.equal(result.program.index, steps.length);
    assert.deepEqual(result.placements, [{ spotId: 's2', duration: 5.5 }, { spotId: 'r2', duration: 3 }]);
    assert.deepEqual(result.receipts, [.35, .35]);
    await page.locator('#timeline').fill('25');
    await page.locator('.field-panel').screenshot({ path: path.join(output, 'replay-3d.png') });
    await page.locator('#view-2d').click(); assert.equal(await page.evaluate(() => fieldApp.displayMode), '2d');
    await page.locator('#timeline').fill('180'); await page.locator('#review-toggle').click();
    const original = await page.evaluate(() => JSON.stringify(fieldApp.sim.snapshot()));
    await page.locator('#review-towers button').first().click(); await page.locator('#review-flip').click();
    assert.equal(await page.evaluate(() => JSON.stringify(fieldApp.sim.snapshot())), original);
    await page.locator('#reset').click(); await page.locator('[data-tab="sequence"]').click();
    const bad = { format: file.format, programs: { redTR: { enabled: true, end: 'wait', steps: [{ type: 'move', destination: 'coordinates', target: { x: 5, y: 5 } }, { type: 'wait', seconds: 1 }] } }, timing: {} };
    await page.locator('#program-file').setInputFiles({ name: 'bad-path.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bad)) });
    await page.locator('#program-robot').selectOption('redTR'); await page.locator('#program-apply').click();
    await page.locator('#next-action').click(); await page.waitForFunction(() => !document.getElementById('next-action').disabled);
    assert.equal(await page.evaluate(() => fieldApp.sim.time), .05);
    assert.ok(await page.evaluate(() => fieldApp.sim.robot('redTR').program.error));
    await page.locator('#next-action').click(); assert.equal(await page.evaluate(() => fieldApp.sim.time), .05);
    await page.locator('#program-skip').click();
    await page.locator('#next-action').click(); await page.waitForFunction(() => fieldApp.sim.robot('redTR').program.index === 2);
    assert.equal(await page.evaluate(() => fieldApp.sim.time), 1.05);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ result, paused, errors }, null, 2));
    console.log(JSON.stringify({ output, result, paused, errors }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
